import { z } from 'zod';
import type { MangelStatus } from './mangel';

export const anzeigeNo = (n: number | null | undefined) => (n ? `MA-${String(n).padStart(3, '0')}` : 'Entwurf');

export const ANZEIGE_STATUS_LABELS = { entwurf: 'Entwurf', versendet: 'Versendet' } as const;
export type AnzeigeStatus = keyof typeof ANZEIGE_STATUS_LABELS;

export const AnzeigeDraft = z.object({
  id: z.string().uuid(), // generated by the client (offline-ready)
  project_id: z.string().uuid(),
  company_id: z.string().uuid(),
  mangel_ids: z.array(z.string().uuid()).min(1, 'Mindestens ein Mangel'),
  deadline: z.string().date(),
  recipient_email: z.string().email().nullish(),
  note: z.string().max(4000).nullish(),
});
export const AnzeigePatch = AnzeigeDraft.omit({ id: true, project_id: true, company_id: true }).partial();

/** Mängel that may become a position: confirmed assignment to this NU, not yet accepted, not in the bin. */
export function canBePosition(m: { status: MangelStatus; assigned_company_id: string | null; assignment_confirmed: boolean; deleted_at?: unknown }, companyId: string) {
  return m.assigned_company_id === companyId && m.assignment_confirmed && m.status !== 'abgenommen' && !m.deleted_at;
}

/** Proposed deadline: the latest open Mangel deadline of the positions, at least 7 days from today (ANNAHME). */
export function proposeDeadline(dueDates: (string | null)[], today = new Date()): string {
  const min = new Date(today.getTime() + 7 * 86_400_000).toISOString().slice(0, 10);
  const latest = dueDates.filter((d): d is string => !!d).sort().at(-1);
  return latest && latest > min ? latest : min;
}
